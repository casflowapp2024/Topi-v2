-------------------------------------------- LAST_MONTH_BALANCE ------------------------------------------

CREATE MATERIALIZED VIEW IF NOT EXISTS LAST_MONTH_BALANCE AS
SELECT T.USER_ID AS USER_ID,
       T.ACCOUNT_ID AS ACCOUNT_ID,
       A.TYPE_ID AS TYPE_ID,
       (SUM(CASE WHEN T.EXPENSE IS FALSE THEN T.AMOUNT ELSE 0 END)
            - SUM(CASE WHEN T.EXPENSE IS TRUE THEN T.AMOUNT ELSE 0 END)
           ) AS BALANCE,
       CURRENT_TIMESTAMP AS UPDATED_AT
FROM TRANSACTIONS AS T
         LEFT JOIN ACCOUNTS AS A ON A.ID = T.ACCOUNT_ID
         LEFT JOIN USER_EXTRA AS U ON T.USER_ID = U.USER_ID
WHERE (T.DATE AT TIME ZONE COALESCE(U.UTC_OFFSET, 'UTC'))::DATE < DATE_TRUNC('month', (NOW() AT TIME ZONE COALESCE(U.UTC_OFFSET, 'UTC')))::DATE
GROUP BY T.USER_ID,
         T.ACCOUNT_ID,
         A.TYPE_ID;

CREATE UNIQUE INDEX IF NOT EXISTS IDX_LAST_MONTH_BALANCE
    ON LAST_MONTH_BALANCE (USER_ID, ACCOUNT_ID);

-------------------------------------------- BALANCE_BY_DATE --------------------------------------
CREATE MATERIALIZED VIEW IF NOT EXISTS BALANCE_BY_DATE AS
SELECT T.USER_ID AS USER_ID,
       (T.DATE AT TIME ZONE COALESCE(U.UTC_OFFSET, 'UTC'))::DATE AS DATE,
       T.ACCOUNT_ID AS ACCOUNT_ID,
       A.TYPE_ID AS TYPE_ID,
       (SUM(CASE WHEN T.EXPENSE IS FALSE THEN T.AMOUNT ELSE 0 END)
           - SUM(CASE WHEN T.EXPENSE IS TRUE THEN T.AMOUNT ELSE 0 END)) AS BALANCE,
       CURRENT_TIMESTAMP AS UPDATED_AT
FROM TRANSACTIONS AS T
         LEFT JOIN ACCOUNTS AS A ON A.ID = T.ACCOUNT_ID
         LEFT JOIN USER_EXTRA AS U ON T.USER_ID = U.USER_ID
GROUP BY T.USER_ID,
         (T.DATE AT TIME ZONE COALESCE(U.UTC_OFFSET, 'UTC'))::DATE,
         T.ACCOUNT_ID,
         A.TYPE_ID
ORDER BY T.USER_ID, DATE DESC, T.ACCOUNT_ID;

CREATE UNIQUE INDEX IF NOT EXISTS IDX_BALANCE_BY_DATE
    ON BALANCE_BY_DATE (USER_ID, ACCOUNT_ID, DATE);

-------------------------------------------- HISTORIC_CUMULATIVE_BALANCE ------------------------------------------

CREATE MATERIALIZED VIEW IF NOT EXISTS HISTORIC_CUMULATIVE_BALANCE AS
(
WITH HISTORIC_CUMULATIVE_BALANCE AS (
    SELECT COALESCE(T.USER_ID, I.USER_ID) AS USER_ID,
           COALESCE(T.UTC_OFFSET, I.UTC_OFFSET) AS UTC_OFFSET,
           COALESCE(T.DATE, I.DATE)::DATE AS DATE,
           SUM(
           SUM(CASE WHEN T.EXPENSE IS FALSE THEN T.AMOUNT ELSE 0 END) -
           SUM(CASE WHEN T.EXPENSE IS TRUE THEN T.AMOUNT ELSE 0 END) +
           COALESCE(MAX(I.INITIAL_BALANCE), 0))
           OVER (PARTITION BY COALESCE(T.USER_ID, I.USER_ID) ORDER BY COALESCE(T.DATE, I.DATE)::DATE) AS CUMULATIVE_BALANCE
    FROM (
             SELECT TR.USER_ID,
                    COALESCE(U.UTC_OFFSET, 'UTC') AS UTC_OFFSET,
                    (TR.DATE AT TIME ZONE COALESCE(U.UTC_OFFSET, 'UTC'))::DATE AS DATE,
                    TR.EXPENSE,
                    TR.AMOUNT
             FROM TRANSACTIONS AS TR
                      LEFT JOIN ACCOUNTS AS A ON A.ID = TR.ACCOUNT_ID AND A.USER_ID = TR.USER_ID
                      LEFT JOIN USER_EXTRA AS U ON TR.USER_ID = U.USER_ID
             WHERE A.TYPE_ID IN (1, 2, 3)
            ) AS T
    FULL JOIN (
        SELECT A.USER_ID,
               COALESCE(U.UTC_OFFSET, 'UTC') AS UTC_OFFSET,
               (A.CREATED_AT AT TIME ZONE COALESCE(U.UTC_OFFSET, 'UTC'))::DATE AS DATE,
               SUM(INITIAL_BALANCE) AS INITIAL_BALANCE
        FROM ACCOUNTS AS A
                 LEFT JOIN USER_EXTRA AS U ON A.USER_ID = U.USER_ID
        WHERE TYPE_ID IN (1, 2, 3)
        GROUP BY A.USER_ID, U.UTC_OFFSET, (A.CREATED_AT AT TIME ZONE COALESCE(U.UTC_OFFSET, 'UTC'))::DATE
        ) AS I
    ON I.DATE = T.DATE AND I.USER_ID = T.USER_ID
    GROUP BY T.USER_ID, I.USER_ID, T.DATE, I.DATE, T.UTC_OFFSET, I.UTC_OFFSET
    HAVING EXTRACT(YEAR FROM COALESCE(T.DATE, I.DATE)) >= EXTRACT(YEAR FROM CURRENT_DATE - INTERVAL '1 YEAR')
),
     USER_MIN_DATE AS (
         SELECT USER_ID,
                UTC_OFFSET,
                MIN(DATE) AS MIN_DATE
         FROM HISTORIC_CUMULATIVE_BALANCE
         GROUP BY USER_ID, UTC_OFFSET
     ),
     DATE_SERIES AS (
         SELECT U.USER_ID,
                GENERATE_SERIES(U.MIN_DATE, (NOW() AT TIME ZONE U.UTC_OFFSET),'1 DAY'::INTERVAL)::DATE AS BALANCE_DATE
         FROM USER_MIN_DATE U
     ),
     BALANCE_WITH_GAPS AS (
         SELECT D.USER_ID,
                D.BALANCE_DATE,
                B.CUMULATIVE_BALANCE AS DAILY_BALANCE
         FROM DATE_SERIES D
                  LEFT JOIN HISTORIC_CUMULATIVE_BALANCE B
                            ON D.USER_ID = B.USER_ID AND D.BALANCE_DATE = B.DATE
     )
SELECT BWG.USER_ID,
       BWG.BALANCE_DATE AS DATE,
       (
           SELECT B2.DAILY_BALANCE
           FROM BALANCE_WITH_GAPS B2
           WHERE B2.USER_ID = BWG.USER_ID AND
               B2.BALANCE_DATE <= BWG.BALANCE_DATE AND
               B2.DAILY_BALANCE IS NOT NULL
           ORDER BY B2.BALANCE_DATE DESC
           LIMIT 1
       ) AS DAILY_BALANCE,
       CURRENT_TIMESTAMP     AS UPDATED_AT
FROM BALANCE_WITH_GAPS BWG
    );

CREATE UNIQUE INDEX IF NOT EXISTS IDX_HISTORIC_BALANCE
    ON HISTORIC_CUMULATIVE_BALANCE (USER_ID, DATE);


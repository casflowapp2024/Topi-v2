-- First, create the enum type
CREATE TYPE WHATSAPP_STATE_ENUM AS ENUM ('verified', 'failed', 'pending', 'blocked');

CREATE TABLE IF NOT EXISTS USER_EXTRA (
    ID BIGSERIAL PRIMARY KEY,
    USER_ID VARCHAR(255) NOT NULL,
    UTC_OFFSET VARCHAR(255) NOT NULL,
    WHATSAPP VARCHAR(255) NOT NUll,
    WHATSAPP_STATE WHATSAPP_STATE_ENUM NOT NULL DEFAULT 'pending',
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

ALTER TABLE USER_EXTRA
    ADD CONSTRAINT UNIQUE_USER_EXTRA UNIQUE (USER_ID);

CREATE INDEX USER_EXTRA_USER_ID ON USER_EXTRA (USER_ID);
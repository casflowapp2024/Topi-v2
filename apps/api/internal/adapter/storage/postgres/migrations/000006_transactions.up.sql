CREATE TABLE IF NOT EXISTS TRANSACTIONS (
    ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    USER_ID VARCHAR(255) NOT NULL,
    CATEGORY_ID BIGINT NOT NULL,
    ACCOUNT_ID BIGINT NOT NULL,
    DESCRIPTION VARCHAR(255) NOT NULL,
    EXPENSE BOOLEAN NOT NULL,
    AMOUNT DECIMAL(10, 2) NOT NULL,
    DATE TIMESTAMP WITH TIME ZONE NOT NULL,
    AUTOMATED BOOLEAN NOT NULL DEFAULT FALSE,
    SHOULD_VERIFY BOOLEAN NOT NULL DEFAULT FALSE,
    CHECKED BOOLEAN NOT NULL DEFAULT TRUE,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

ALTER TABLE TRANSACTIONS
    ADD CONSTRAINT "FK_CATEGORY_TRANSACTION" FOREIGN KEY (CATEGORY_ID, USER_ID) REFERENCES CATEGORIES (ID, USER_ID) ON UPDATE CASCADE;

ALTER TABLE TRANSACTIONS
    ADD CONSTRAINT "FK_ACCOUNT_TRANSACTION" FOREIGN KEY (ACCOUNT_ID, USER_ID) REFERENCES ACCOUNTS (ID, USER_ID) ON UPDATE CASCADE;

CREATE INDEX TRANSACTION_USER ON TRANSACTIONS (USER_ID, DATE);
CREATE OR REPLACE VIEW CURATED_TRANSACTIONS AS
SELECT (T.DATE AT TIME ZONE COALESCE(U.UTC_OFFSET, 'UTC'))::DATE AS DATE,
       T.USER_ID                                                 AS USER_ID,
       COALESCE(U.UTC_OFFSET, 'UTC')                             AS UTC_OFFSET,
       (CASE WHEN T.EXPENSE THEN -1 ELSE 1 END) * T.AMOUNT *
       (CASE WHEN C.INCOME IS TRUE AND A.TYPE_ID IN (1, 2, 3) THEN 1 ELSE 0 END) AS INCOME,

       (CASE WHEN T.EXPENSE THEN -1 ELSE 1 END) * T.AMOUNT *
       (CASE WHEN C.INCOME IS FALSE AND A.TYPE_ID IN (1, 2, 4) THEN 1 ELSE 0 END) AS EXPENSE,

       (CASE WHEN T.EXPENSE THEN -1 ELSE 1 END) * T.AMOUNT *
       (CASE WHEN C.INCOME IS FALSE AND A.TYPE_ID IN (1, 2, 3) THEN 1 ELSE 0 END) AS SAVINGS_EXPENSE,

       (CASE WHEN T.EXPENSE THEN -1 ELSE 1 END) * T.AMOUNT *
       (CASE WHEN C.INCOME IS FALSE AND A.TYPE_ID = 4 THEN 1 ELSE 0 END) AS DEBT
FROM TRANSACTIONS AS T
         LEFT JOIN ACCOUNTS AS A ON A.ID = T.ACCOUNT_ID AND A.USER_ID = T.USER_ID
         LEFT JOIN USER_EXTRA AS U ON T.USER_ID = U.USER_ID
         LEFT JOIN CATEGORIES AS C ON T.CATEGORY_ID = C.ID
;


CREATE OR REPLACE VIEW CURATED_INITIAL_BALANCE AS
SELECT A.USER_ID                                                               AS USER_ID,
       COALESCE(U.UTC_OFFSET, 'UTC')                                           AS UTC_OFFSET,
       (A.CREATED_AT AT TIME ZONE COALESCE(U.UTC_OFFSET, 'UTC'))::DATE         AS DATE,
       SUM(CASE WHEN A.TYPE_ID IN (1, 2, 3) THEN A.INITIAL_BALANCE ELSE 0 END) AS SAVINGS_INITIAL_BALANCE,
       SUM(CASE WHEN A.TYPE_ID IN (4) THEN A.INITIAL_BALANCE ELSE 0 END)       AS CREDITS_INITIAL_BALANCE
FROM ACCOUNTS AS A
         LEFT JOIN USER_EXTRA AS U ON A.USER_ID = U.USER_ID
GROUP BY A.USER_ID, U.UTC_OFFSET,
         (A.CREATED_AT AT TIME ZONE COALESCE(U.UTC_OFFSET, 'UTC'))::DATE;


CREATE OR REPLACE VIEW FINANCIAL_SUMMARY_BY_DAY AS
SELECT COALESCE(CT.USER_ID, CI.USER_ID)                                    AS USER_ID,
       COALESCE(CT.DATE, CI.DATE)::DATE                                    AS DATE,
       EXTRACT(YEAR FROM COALESCE(CT.DATE, CI.DATE)::DATE)                 AS YEAR,
       EXTRACT(MONTH FROM COALESCE(CT.DATE, CI.DATE)::DATE)                AS MONTH,
       COALESCE(CT.UTC_OFFSET, CI.UTC_OFFSET)                              AS UTC_OFFSET,
       SUM(COALESCE(CT.INCOME, 0))                                         AS INCOME,
       SUM(COALESCE(CT.EXPENSE, 0))                                        AS EXPENSE,
       SUM(COALESCE(CT.INCOME, 0)) + SUM(COALESCE(CT.EXPENSE, 0))          AS SAVINGS,
       SUM(COALESCE(CT.INCOME, 0)) + SUM(COALESCE(CT.SAVINGS_EXPENSE, 0)) +
       COALESCE(MAX(CI.SAVINGS_INITIAL_BALANCE), 0)                        AS SAVINGS_BALANCE,
       SUM(COALESCE(CT.DEBT, 0) + COALESCE(CI.CREDITS_INITIAL_BALANCE, 0)) AS CREDITS_BALANCE
FROM CURATED_TRANSACTIONS AS CT
         FULL JOIN CURATED_INITIAL_BALANCE AS CI
                   ON CI.DATE = CT.DATE AND CI.USER_ID = CT.USER_ID
GROUP BY CT.USER_ID, CI.USER_ID, CT.DATE, CI.DATE, CT.UTC_OFFSET, CI.UTC_OFFSET
HAVING EXTRACT(YEAR FROM COALESCE(CT.DATE, CI.DATE)) >=
       EXTRACT(YEAR FROM CURRENT_DATE - INTERVAL '1 YEAR');


CREATE OR REPLACE VIEW DATE_SERIES AS
SELECT USER_ID,
       GENERATE_SERIES(MIN_DATE, (NOW() AT TIME ZONE UTC_OFFSET), '1 DAY'::INTERVAL)::DATE AS DATE
FROM (SELECT USER_ID,
             UTC_OFFSET,
             MIN(DATE) AS MIN_DATE
      FROM FINANCIAL_SUMMARY_BY_DAY
      GROUP BY USER_ID, UTC_OFFSET
     ) AS MIN_DATE;


CREATE OR REPLACE VIEW DAILY_FINANCIAL_SUMMARY AS
SELECT DS.USER_ID,
       DS.DATE,
       COALESCE(FSB.YEAR, EXTRACT(YEAR FROM DS.DATE))   AS YEAR,
       COALESCE(FSB.MONTH, EXTRACT(MONTH FROM DS.DATE)) AS MONTH,
       COALESCE(FSB.INCOME, 0)                          AS INCOME,
       COALESCE(FSB.EXPENSE, 0)                         AS EXPENSE,
       COALESCE(FSB.SAVINGS, 0)                         AS SAVINGS,
       COALESCE(FSB.SAVINGS_BALANCE, 0)                 AS SAVINGS_BALANCE,
       COALESCE(FSB.CREDITS_BALANCE, 0)                 AS CREDITS_BALANCE
FROM DATE_SERIES AS DS
         LEFT JOIN FINANCIAL_SUMMARY_BY_DAY AS FSB
                   ON DS.USER_ID = FSB.USER_ID AND DS.DATE = FSB.DATE;


CREATE OR REPLACE VIEW DAILY_ROLLING_BALANCE AS
SELECT USER_ID,
       DATE,
       SUM(SAVINGS_BALANCE) OVER (PARTITION BY USER_ID ORDER BY DATE) AS SAVINGS_BALANCE,
       SUM(CREDITS_BALANCE) OVER (PARTITION BY USER_ID ORDER BY DATE) AS CREDITS_BALANCE
FROM DAILY_FINANCIAL_SUMMARY;


CREATE OR REPLACE VIEW DAILY_FULL_FINANCIAL_SUMMARY AS
SELECT USER_ID,
       DATE,
       INCOME,
       EXPENSE,
       SUM(INCOME) OVER (PARTITION BY USER_ID, YEAR, MONTH ORDER BY DATE)    AS MTD_INCOME,
       SUM(EXPENSE) OVER (PARTITION BY USER_ID, YEAR, MONTH ORDER BY DATE)   AS MTD_EXPENSE,
       SUM(SAVINGS) OVER (PARTITION BY USER_ID, YEAR, MONTH ORDER BY DATE)   AS MTD_SAVINGS
FROM DAILY_FINANCIAL_SUMMARY;


CREATE OR REPLACE VIEW MONTHLY_FINANCIAL_SUMMARY AS
SELECT USER_ID,
       YEAR,
       MONTH,
       SUM(INCOME)                                                                              AS INCOME,
       SUM(EXPENSE)                                                                             AS EXPENSE,
       SUM(SAVINGS)                                                                             AS SAVINGS,
       SUM(SAVINGS_BALANCE)                                                                     AS SAVINGS_BALANCE,
       SUM(CREDITS_BALANCE)                                                                     AS CREDITS_BALANCE,
       COALESCE(LAG(SUM(INCOME), 1, NULL) OVER (PARTITION BY USER_ID ORDER BY YEAR, MONTH), 0)  AS INCOME_PAST,
       COALESCE(LAG(SUM(EXPENSE), 1, NULL) OVER (PARTITION BY USER_ID ORDER BY YEAR, MONTH), 0) AS EXPENSE_PAST,
       COALESCE(LAG(SUM(SAVINGS), 1, NULL) OVER (PARTITION BY USER_ID ORDER BY YEAR, MONTH), 0) AS SAVINGS_PAST

FROM DAILY_FINANCIAL_SUMMARY
GROUP BY USER_ID, YEAR, MONTH
ORDER BY USER_ID, YEAR, MONTH DESC;


CREATE OR REPLACE VIEW MONTHLY_ROLLING_BALANCE_BASE AS
SELECT
    USER_ID,
    YEAR,
    MONTH,
    SUM(SAVINGS_BALANCE) OVER (PARTITION BY USER_ID ORDER BY YEAR, MONTH) AS SAVINGS_BALANCE,
    SUM(CREDITS_BALANCE) OVER (PARTITION BY USER_ID ORDER BY YEAR, MONTH) AS CREDITS_BALANCE
FROM MONTHLY_FINANCIAL_SUMMARY;


CREATE OR REPLACE VIEW MONTHLY_ROLLING_BALANCE AS
SELECT
    USER_ID,
    YEAR,
    MONTH,
    SAVINGS_BALANCE,
    COALESCE(LAG(SAVINGS_BALANCE) OVER (PARTITION BY USER_ID ORDER BY YEAR, MONTH), 0) AS SAVINGS_BALANCE_PAST,
    CREDITS_BALANCE,
    COALESCE(LAG(CREDITS_BALANCE) OVER (PARTITION BY USER_ID ORDER BY YEAR, MONTH), 0) AS CREDITS_BALANCE_PAST
FROM MONTHLY_ROLLING_BALANCE_BASE;


CREATE MATERIALIZED VIEW IF NOT EXISTS DAILY_ANALYSIS AS
SELECT DRB.USER_ID,
       DRB.DATE,
       DFS.INCOME              AS INCOME,
       DFS.EXPENSE             AS EXPENSE,
       DFS.MTD_INCOME          AS MTD_INCOME,
       DFS.MTD_EXPENSE         AS MTD_EXPENSE,
       DFS.MTD_SAVINGS         AS MTD_SAVINGS,
       DRB.SAVINGS_BALANCE     AS RUNNING_SAVINGS_BALANCE,
       DRB.CREDITS_BALANCE     AS RUNNING_CREDITS_BALANCE,
       CURRENT_TIMESTAMP       AS UPDATED_AT
FROM DAILY_ROLLING_BALANCE AS DRB
         JOIN DAILY_FULL_FINANCIAL_SUMMARY AS DFS
              ON DRB.USER_ID = DFS.USER_ID AND DRB.DATE = DFS.DATE;



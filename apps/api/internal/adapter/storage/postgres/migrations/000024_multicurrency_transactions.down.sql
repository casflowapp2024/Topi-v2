CREATE MATERIALIZED VIEW IF NOT EXISTS MONTHLY_ANALYSIS AS
SELECT MFS.USER_ID,
       MFS.YEAR,
       MFS.MONTH,
       MFS.INCOME               AS INCOME,
       MFS.INCOME_PAST          AS INCOME_PAST,
       MFS.EXPENSE              AS EXPENSE,
       MFS.EXPENSE_PAST         AS EXPENSE_PAST,

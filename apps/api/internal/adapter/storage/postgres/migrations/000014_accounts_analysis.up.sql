CREATE OR REPLACE VIEW CURATED_TRANSACTIONS_BY_ACCOUNTS AS
SELECT T.USER_ID                                                   AS USER_ID,
       T.ACCOUNT_ID                                                AS ACCOUNT_ID,
       A.NAME                                                      AS ACCOUNT_NAME,
       (T.DATE AT TIME ZONE COALESCE(U.UTC_OFFSET, 'UTC'))::DATE   AS DATE,
       COALESCE(U.UTC_OFFSET, 'UTC')                               AS UTC_OFFSET,
       (CASE WHEN T.EXPENSE THEN 0 ELSE 1 END) * T.AMOUNT          AS INCOME,
       (CASE WHEN T.EXPENSE THEN -1 ELSE 0 END) * T.AMOUNT         AS EXPENSE
FROM TRANSACTIONS AS T
         LEFT JOIN ACCOUNTS AS A ON A.ID = T.ACCOUNT_ID AND A.USER_ID = T.USER_ID
         LEFT JOIN USER_EXTRA AS U ON T.USER_ID = U.USER_ID
         LEFT JOIN CATEGORIES AS C ON T.CATEGORY_ID = C.ID
;

CREATE OR REPLACE VIEW INITIAL_BALANCE_BY_ACCOUNTS AS
SELECT A.USER_ID                                                       AS USER_ID,
       A.ID                                                            AS ACCOUNT_ID,
       A.NAME                                                          AS ACCOUNT_NAME,
       A.INITIAL_BALANCE                                               AS INITIAL_BALANCE,
       (A.CREATED_AT AT TIME ZONE COALESCE(U.UTC_OFFSET, 'UTC'))::DATE AS DATE
FROM ACCOUNTS AS A
         LEFT JOIN USER_EXTRA AS U ON A.USER_ID = U.USER_ID
;

CREATE OR REPLACE VIEW DAILY_ACCOUNTS_REPORT_SUMMARY AS
SELECT COALESCE(C.USER_ID, I.USER_ID)                     AS USER_ID,
       COALESCE(C.DATE, I.DATE)                           AS DATE,
       COALESCE(C.ACCOUNT_ID, I.ACCOUNT_ID)               AS ACCOUNT_ID,
       COALESCE(C.ACCOUNT_NAME, I.ACCOUNT_NAME)           AS ACCOUNT_NAME,
       EXTRACT(YEAR FROM COALESCE(C.DATE, I.DATE)::DATE)  AS YEAR,
       EXTRACT(MONTH FROM COALESCE(C.DATE, I.DATE)::DATE) AS MONTH,
       COALESCE(I.INITIAL_BALANCE, 0)                     AS INITIAL_BALANCE,
       COALESCE(C.INCOME, 0)                              AS INCOME,
       COALESCE(C.EXPENSE, 0)                             AS EXPENSE,
       COALESCE(I.INITIAL_BALANCE, 0) + COALESCE(C.INCOME, 0) +
       COALESCE(C.EXPENSE, 0)                             AS BALANCE

FROM CURATED_TRANSACTIONS_BY_ACCOUNTS AS C
         FULL JOIN INITIAL_BALANCE_BY_ACCOUNTS AS I
                   ON C.USER_ID = I.USER_ID AND
                      C.ACCOUNT_ID = I.ACCOUNT_ID AND
                      C.DATE = I.DATE
;

CREATE OR REPLACE VIEW MONTHLY_ACCOUNTS_SUMMARY AS
SELECT USER_ID,
       YEAR,
       MONTH,
       ACCOUNT_ID,
       ACCOUNT_NAME,
       SUM(BALANCE) AS BALANCE,
       COALESCE(LAG(SUM(BALANCE), 1, NULL)
                OVER (PARTITION BY USER_ID, ACCOUNT_ID ORDER BY YEAR, MONTH),
                0)  AS BALANCE_PAST
FROM DAILY_ACCOUNTS_REPORT_SUMMARY
GROUP BY USER_ID, YEAR, MONTH, ACCOUNT_ID, ACCOUNT_NAME
;

CREATE MATERIALIZED VIEW IF NOT EXISTS MONTHLY_ACCOUNTS_ANALYSIS AS
SELECT M.USER_ID,
       M.YEAR,
       M.MONTH,
       M.ACCOUNT_ID,
       A.TYPE_ID,
       M.ACCOUNT_NAME,
       SUM(M.BALANCE) OVER (PARTITION BY M.USER_ID, M.ACCOUNT_ID ORDER BY M.YEAR, M.MONTH) AS BALANCE,
       SUM(M.BALANCE_PAST) OVER (PARTITION BY M.USER_ID, M.ACCOUNT_ID ORDER BY M.YEAR, M.MONTH) AS BALANCE_PAST
FROM MONTHLY_ACCOUNTS_SUMMARY AS M
    LEFT JOIN ACCOUNTS AS A ON M.USER_ID = A.USER_ID AND M.ACCOUNT_ID = A.ID
    ORDER BY USER_ID, ACCOUNT_ID, ACCOUNT_NAME, YEAR, MONTH;

CREATE UNIQUE INDEX IF NOT EXISTS MONTHLY_ACCOUNTS_ANALYSIS_USER_ACCOUNT_DATE_IDX
    ON MONTHLY_ACCOUNTS_ANALYSIS (USER_ID, ACCOUNT_ID, YEAR, MONTH);

SELECT cron.schedule('monthly_accounts_analysis', '*/5 * * * *', 'REFRESH MATERIALIZED VIEW CONCURRENTLY MONTHLY_ACCOUNTS_ANALYSIS');
